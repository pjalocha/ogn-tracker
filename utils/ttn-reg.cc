static int PrintHex(char *Out, const uint8_t *Byte, int Len, const char *Format="%02X")
{ int OutLen=0;
  for(int Idx=0; Idx<Len; Idx++) OutLen+=sprintf(Out+OutLen, Format, Byte[Idx]);
  return OutLen; }

