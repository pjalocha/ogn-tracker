struct JPEGError
{ jpeg_error_mgr Pub;
  jmp_buf Jump; };

static void JPEGErrorExit(j_common_ptr Info)
{ JPEGError *Error=(JPEGError *)Info->err;
  (*Info->err->format_message)(Info, Error->Pub.msg_parm.s);
  longjmp(Error->Jump, 1); }

static bool LoadJPEG(const char *Filename, std::vector<uint8_t> &Pixels, int &Width, int &Height)
{ FILE *File=fopen(Filename, "rb");
  if(!File) { perror(Filename); return false; }

  jpeg_decompress_struct Info;
  JPEGError Error;
  Info.err=jpeg_std_error(&Error.Pub);
  Error.Pub.error_exit=JPEGErrorExit;
  if(setjmp(Error.Jump))
  { fprintf(stderr, "Cannot decode JPEG %s: %s\n", Filename, Error.Pub.msg_parm.s);
    jpeg_destroy_decompress(&Info); fclose(File); return false; }

  jpeg_create_decompress(&Info);
  jpeg_stdio_src(&Info, File);
  if(jpeg_read_header(&Info, TRUE)!=JPEG_HEADER_OK)
  { fprintf(stderr, "Cannot read JPEG header: %s\n", Filename);
    jpeg_destroy_decompress(&Info); fclose(File); return false; }
  Info.out_color_space=JCS_GRAYSCALE;
  jpeg_start_decompress(&Info);
  Width=(int)Info.output_width; Height=(int)Info.output_height;
  if(Width<=0 || Height<=0 || Info.output_components!=1)
  { fprintf(stderr, "Unsupported JPEG dimensions or pixel format: %s\n", Filename);
    jpeg_destroy_decompress(&Info); fclose(File); return false; }
  Pixels.resize((size_t)Width*(size_t)Height);
  while(Info.output_scanline<Info.output_height)
  { JSAMPLE *Row=Pixels.data()+(size_t)Info.output_scanline*(size_t)Width;
    JSAMPLE *Rows[1]={Row}; jpeg_read_scanlines(&Info, Rows, 1); }
  jpeg_finish_decompress(&Info);
  jpeg_destroy_decompress(&Info); fclose(File);
  return true; }

struct ZXingAPI
{ typedef void *(*ImageViewNewFn)(const uint8_t *, int, int, int, int, int);
  typedef void (*ImageViewDeleteFn)(void *);
  typedef void *(*ReaderOptionsNewFn)();
  typedef void (*ReaderOptionsDeleteFn)(void *);
  typedef void (*ReaderOptionsBoolFn)(void *, bool);
  typedef void *(*ReadBarcodesFn)(const void *, const void *);
  typedef int (*BarcodesSizeFn)(const void *);
  typedef const void *(*BarcodesAtFn)(const void *, int);
  typedef uint8_t *(*BarcodeBytesFn)(const void *, int *);
  typedef void (*BarcodesDeleteFn)(void *);
  typedef void (*FreeFn)(void *);

  void *Library;
  ImageViewNewFn ImageViewNew;
  ImageViewDeleteFn ImageViewDelete;
  ReaderOptionsNewFn ReaderOptionsNew;
  ReaderOptionsDeleteFn ReaderOptionsDelete;
  ReaderOptionsBoolFn SetTryHarder;
  ReaderOptionsBoolFn SetTryRotate;
  ReadBarcodesFn ReadBarcodes;
  BarcodesSizeFn BarcodesSize;
  BarcodesAtFn BarcodesAt;
  BarcodeBytesFn BarcodeBytes;
  BarcodesDeleteFn BarcodesDelete;
  FreeFn Free;

  ZXingAPI():Library(0),ImageViewNew(0),ImageViewDelete(0),ReaderOptionsNew(0),
    ReaderOptionsDelete(0),SetTryHarder(0),SetTryRotate(0),ReadBarcodes(0),
    BarcodesSize(0),BarcodesAt(0),BarcodeBytes(0),BarcodesDelete(0),Free(0) {}

  template <typename Type> bool Get(Type &Function, const char *Name)
  { Function=reinterpret_cast<Type>(dlsym(Library, Name)); return Function!=0; }

  bool Open()
  { const char *Names[]={"libZXing.so.3", "libZXing.so", 0};
    for(int Idx=0; Names[Idx] && !Library; Idx++) Library=dlopen(Names[Idx], RTLD_LAZY);
    if(!Library)
    { fprintf(stderr, "QR decoder libZXing was not found (install the ZXing C++ runtime)\n"); return false; }
    bool Good=true;
    Good&=Get(ImageViewNew, "ZXing_ImageView_new");
    Good&=Get(ImageViewDelete, "ZXing_ImageView_delete");
    Good&=Get(ReadBarcodes, "ZXing_ReadBarcodes");
    Good&=Get(BarcodesSize, "ZXing_Barcodes_size");
    Good&=Get(BarcodesAt, "ZXing_Barcodes_at");
    Good&=Get(BarcodeBytes, "ZXing_Barcode_bytes");
    Good&=Get(BarcodesDelete, "ZXing_Barcodes_delete");
    Good&=Get(Free, "ZXing_free");
    // These options are optional; the core decoder works without them.
    Get(ReaderOptionsNew, "ZXing_ReaderOptions_new");
    Get(ReaderOptionsDelete, "ZXing_ReaderOptions_delete");
    Get(SetTryHarder, "ZXing_ReaderOptions_setTryHarder");
    Get(SetTryRotate, "ZXing_ReaderOptions_setTryRotate");
    if(!Good)
    { fprintf(stderr, "The installed libZXing does not provide the required C API\n"); Close(); return false; }
    return true; }

  void Close()
  { if(Library) dlclose(Library); Library=0; }
};

static bool DecodeQR(const char *Filename, uint64_t &DecodedDevEUI, uint8_t DecodedAppKey[16])
{ std::vector<uint8_t> Pixels; int Width=0, Height=0;
  if(!LoadJPEG(Filename, Pixels, Width, Height)) return false;
  ZXingAPI API;
  if(!API.Open()) return false;

  // ZXing_ImageFormat_Lum from ZXingC.h; the image is one byte per pixel.
  void *Image=API.ImageViewNew(Pixels.data(), Width, Height, 0x01000000, Width, 1);
  if(!Image)
  { fprintf(stderr, "Could not create ZXing image view\n"); API.Close(); return false; }
  void *Options=API.ReaderOptionsNew ? API.ReaderOptionsNew() : 0;
  if(Options && API.SetTryHarder) API.SetTryHarder(Options, true);
  if(Options && API.SetTryRotate) API.SetTryRotate(Options, true);
  void *Barcodes=API.ReadBarcodes(Image, Options);
  bool Found=false;
  if(Barcodes)
  { int Count=API.BarcodesSize(Barcodes);
    for(int Idx=0; Idx<Count && !Found; Idx++)
    { const void *Barcode=API.BarcodesAt(Barcodes, Idx); int Length=0;
      uint8_t *Bytes=Barcode ? API.BarcodeBytes(Barcode, &Length) : 0;
      if(Bytes && Length==24)
      { DecodedDevEUI=0;
        for(int Byte=0; Byte<8; Byte++) DecodedDevEUI=(DecodedDevEUI<<8)|Bytes[Byte];
        memcpy(DecodedAppKey, Bytes+8, 16); Found=true; }
      if(Bytes) API.Free(Bytes); }
    API.BarcodesDelete(Barcodes); }
  if(Options && API.ReaderOptionsDelete) API.ReaderOptionsDelete(Options);
  API.ImageViewDelete(Image); API.Close();
  if(!Found) fprintf(stderr, "No 24-byte OGN registration QR payload found in %s\n", Filename);
  return Found; }

